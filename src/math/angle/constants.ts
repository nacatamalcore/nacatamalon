/**
 * A full turn in radians (2π): the period of the trig functions. Useful for
 * expressing whole rotations and for wrapping angles back into range.
 *
 * @category Math
 * @since 1.0.0
 * @author Francisco Pereira Alvarado
 */
export const TAU = Math.PI * 2;

/**
 * Conversion factor from degrees to radians (π / 180). `degToRad` multiplies by this.
 *
 * @since 1.0.0
 */
export const DEG2RAD = Math.PI / 180;

/**
 * Conversion factor from radians to degrees (180 / π). `radToDeg` multiplies by this.
 *
 * @since 1.0.0
 */
export const RAD2DEG = 180 / Math.PI;
